function translateString(str) {
  if (typeof str !== 'string') return str;
  let res = str;
  for (const [re, rep] of replacements) {
    res = res.replace(re, rep);
  }
  return res;
}

function deepTranslate(mrObj, enObj) {
  const result = {};
  for (const k in enObj) {
    if (typeof enObj[k] === 'object' && enObj[k] !== null && !Array.isArray(enObj[k])) {
      result[k] = deepTranslate(mrObj?.[k] || {}, enObj[k]);
    } else {
      const mrVal = mrObj?.[k] || enObj[k];
      result[k] = translateString(mrVal);
    }
  }
  return result;
}

